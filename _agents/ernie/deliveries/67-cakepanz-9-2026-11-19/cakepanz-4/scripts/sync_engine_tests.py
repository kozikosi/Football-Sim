#!/usr/bin/env python3
"""sync_engine_tests.py — re-point the carried engine test suite at a fresh snapshot copy.

The shell carries the Architect's own suite (colors/test at the pin) under test/engine/, with the
ONLY change being import paths: `colors/src/…` → `src/engine/…` (SNAPSHOT.md's contract: the suite
is re-pointed, never edited). This script rewrites those import specifiers in every *.ts file under
test/engine/ and makes sure the root entry file (test/engine.test.ts) imports every suite file, so
a re-pin that adds suites runs them all. Run it after extracting a new pin's colors/test:

    git archive <PIN> colors/test | tar -x --strip-components=2 -C /tmp/ct
    rsync -a /tmp/ct/ test/engine/ && python3 scripts/sync_engine_tests.py

It also prints a summary of files touched. Idempotent: running twice changes nothing the second time.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TEST_DIR = ROOT / "test" / "engine"
ENTRY = ROOT / "test" / "engine.test.ts"

# colors/test files reference the engine relatively — both import specifiers ('../../src/…')
# and runtime URLs (new URL('../../src/sports/…', import.meta.url)). One textual pattern covers
# both: any run of ../ followed by src/ NOT followed by engine/ is a colors/src reference that
# must become this file's own relative path down to <root>/src/engine.
COLORS_SRC_RE = re.compile(r"((?:\.\./)+)src/(?!engine/)")

def main() -> int:
    if not TEST_DIR.is_dir():
        print(f"ABORT: {TEST_DIR} does not exist"); return 1
    touched = []
    for path in sorted(TEST_DIR.rglob("*.ts")):
        depth = len(path.parent.relative_to(ROOT).parts)  # dirs below the repo root
        prefix = "../" * depth + "src/engine/"
        text = path.read_text(encoding="utf-8")
        new = COLORS_SRC_RE.sub(lambda m: f"{prefix}", text)
        if new != text:
            path.write_text(new, encoding="utf-8")
            touched.append(path.relative_to(ROOT))
    # keep the entry file importing every suite file (relative ./engine/… specifiers)
    suites = sorted(
        p for p in TEST_DIR.rglob("*.test.ts") if p.name not in ("fixture.ts",)
    )
    lines = ["/* engine.test.ts — the pin's own suite, carried and re-pointed (colors/src → src/engine).",
             "   Regenerated by scripts/sync_engine_tests.py at the re-pin; every suite file is imported here. */"]
    for s in suites:
        rel = s.relative_to(TEST_DIR.parent)  # engine/… WITH the .ts extension (strip-types needs explicit extensions)
        lines.append(f"import './{rel.as_posix()}';")
    if ENTRY.exists() and ENTRY.read_text(encoding="utf-8") != "\n".join(lines) + "\n":
        ENTRY.write_text("\n".join(lines) + "\n", encoding="utf-8")
        touched.append(ENTRY.relative_to(ROOT))
    print(f"suites found: {len(suites)}")
    print(f"files touched: {len(touched)}")
    for t in touched:
        print(f"  {t}")
    return 0

if __name__ == "__main__":
    sys.exit(main())
