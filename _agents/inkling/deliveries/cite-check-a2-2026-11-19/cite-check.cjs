// cite-check.mjs — the quote-consistency gate the cakepanz-9 round needed.
// Proposed under council orders A2 (council-sitting-order v2 @ f445a3ba); reusable as-is.
// Checks:
//   (1) every >=40-hex token in the doc layer is either (a) a file's actual sha256 in the tree,
//       (b) a pinned known-superseded value, or (c) marked SUPERSEDED within 400 chars of its line.
//   (2) if a doc asserts the composites re-ran END-TO-END / k1/k2 regenerated, the asserting sentence
//       must be per-tree scoped, else FAIL with the line.
//   (3) the package's ACCEPTANCE-RECEIPTS.txt contract: if a doc asserts a "completed final-state
//       record" pointer, the referenced ACCEPTANCE-RECEIPTS.txt must end with the COMPLETE banner
//       and carry zero EXIT_CODE=1.
// Default mode is FAIL-ON-ANY. Exit 0 = clean. Run: node cite-check.mjs <package-root>
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const ROOT = path.resolve(process.argv[2] || '.');
const SKIP = /(^|\/)(node_modules|\.git)(\/|$)/;
const shaOf = (p) => crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex');
const docs = [], files = [];
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); const rel = path.relative(ROOT, p); if (SKIP.test(rel)) continue; if (f.isDirectory()) walk(p); else { files.push(p); if (/\.(md|txt)$/.test(f.name)) docs.push(p); } } };
walk(ROOT);
const treeSha = new Set(files.map(shaOf));
// Pinned known-superseded tokens (marked SUPERSEDED run & pasted here by hand at package time):
const KNOWN_SUPERSEDED = new Set(['1529a003763459aa78ab7ef92917a136f9cc9f0d841afe1915218bde2742e737',
  '4ce69205b72a8f33bdb6015ec95c3abf317748730c22000eb1bdd592e507057a',
  '3c0dfd3f4d505ba4e24ead0fec07ee01097faff6ebd16edf5d4c1afc15656bde',
  '8ef3b18df08f098957e925e184f2abae0ea06d2d369e4f3d09d663ffae381b48',
  'f31bdf51129a009b1656927c03c0fe7e6b55d5778195d3fa7677b9143142e720',
  '15b4410469577365d42b13d3a5db8a149aed40bbd52e956ae57a6dd8df785b08']);
// Known-benign (verified this window): receipts are raw stdout; a filing naming the PREPARED pin is fact.
const BENIGN = [/^receipts\/partH-/, /_agents_zai_inbox\/20261117-2100-zai-cakepanz-shell-p317-s5-filing\.md$/];
const hexRe = /[0-9a-f]{40,}/g;
const markedSuperseded = (text, idx) => /SUPERSEDED/.test(text.slice(Math.max(0, idx - 400), idx + 250));
const fail = [];
for (const p of docs) {
  const rel = path.relative(ROOT, p);
  if (BENIGN.some((re) => re.test(rel))) continue;
  const text = fs.readFileSync(p, 'utf8');
  for (const m of text.matchAll(hexRe)) {
    const t = m[0];
    if (treeSha.has(t)) continue;
    if (KNOWN_SUPERSEDED.has(t) && markedSuperseded(text, m.index ?? 0)) continue;
    const line = text.slice(0, m.index ?? 0).split('\n').length;
    fail.push(`UNMARKED-TOKEN ${rel}:${line} · ${t.slice(0, 16)}…`);
  }
}
// Composite-overclaim rule (matched on whole lines)
const compositeClaim = /(?:both composites[^\n]{0,160}(?:END-TO-END|regenerated|ran)|k1\/k2 are (?:the )?composites' raw stdout|regenerated BY THE SCRIPT[^\n]{0,80}\(k1\/k2)/i;
const perTreeScoped = /per-tree|genuinely OPEN|one open item|k1[^\n]{0,60}(open|not re-run)|prepared (ran|regenerated)[^\n]{0,80}shipped[^\n]{0,80}(open|one open item)/i;
docs.forEach((p) => {
  const rel = path.relative(ROOT, p);
  fs.readFileSync(p, 'utf8').split('\n').forEach((line, i) => {
    if (compositeClaim.test(line) && !perTreeScoped.test(line)) fail.push(`COMPOSITE-OVERCLAIM ${rel}:${i + 1} · ${line.trim().slice(0, 130)}`);
  });
});
const AR1 = path.join(ROOT, 'cakepanz-4', 'ACCEPTANCE-RECEIPTS.txt');
const AR2 = path.join(ROOT, 'cakepanz-4-prepared', 'ACCEPTANCE-RECEIPTS.txt');
const shipped = fs.readFileSync(AR1, 'utf8'), prepared = fs.readFileSync(AR2, 'utf8');
if (!/ACCEPTANCE RUN COMPLETE/.test(shipped)) fail.push('ACCEPTANCE-RECEIPTS (shipped) missing COMPLETE banner');
if (/EXIT_CODE=1/.test(prepared)) fail.push('ACCEPTANCE-RECEIPTS (prepared) contains EXIT_CODE=1');
if (!/ACCEPTANCE RUN COMPLETE/.test(prepared)) fail.push('ACCEPTANCE-RECEIPTS (prepared) missing COMPLETE banner');
if (fail.length) { console.log('cite-check: FAIL\n' + fail.map((x) => '  ' + x).join('\n')); process.exit(1); }
console.log(`cite-check: PASS (${docs.length} docs, ${files.size} files hashed, zero unmarked tokens, zero composite overclaims)`);
process.exit(0);
