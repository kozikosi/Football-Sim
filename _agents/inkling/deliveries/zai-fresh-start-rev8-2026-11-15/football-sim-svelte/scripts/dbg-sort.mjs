import { pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';
const _req = createRequire(import.meta.url);
const pw = _req('playwright');
const browser = await pw.chromium.launch({ args: ['--no-sandbox', '--allow-file-access-from-files'] });
const page = await browser.newPage();
page.on('pageerror', (e) => console.log('PAGEERROR', String(e).slice(0, 200)));
page.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE', m.text().slice(0, 200)); });
await page.goto(pathToFileURL(process.cwd() + '/dist/index.html').href);
await page.waitForSelector('[data-testid="app-shell"]');
await page.click('[data-testid="nav-stats"]');
await page.waitForSelector('[data-testid="stats-table"]');
const r0a = await page.locator('[data-testid="stats-row-0"] td').allTextContents();
await page.click('[data-testid="stats-sort-ovr"]');
await page.waitForTimeout(200);
const r0b = await page.locator('[data-testid="stats-row-0"] td').allTextContents();
const hdr = await page.locator('[data-testid="stats-sort-ovr"]').textContent();
console.log('before:', r0a.slice(0, 5), '· after:', r0b.slice(0, 5), '· hdr:', hdr);
await browser.close();
