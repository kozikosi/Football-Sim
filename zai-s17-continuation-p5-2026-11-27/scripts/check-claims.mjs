/* check-claims.mjs — the T2 claims protocol (2026-11-24, the orcads F2 fix).
 *
 * The 2026-11-23 verifier RED was a mis-specified LITERAL expectation ("37 pass · 0 fail") that
 * the package author resolved in prose — the independence pattern the council exists to prevent.
 * This file makes that class impossible: every claim a reviewer would test is a machine-readable
 * assertion over real files (regex/count/seal/recomputation), matched against the formats the
 * tools ACTUALLY print (node:test's "ℹ pass 37", the batteries' "· N pass · 0 fail" banners).
 * A RED is a failing line + exit 1 — never a paragraph. The original RED + its resolution stay
 * on record at deliveries/receipts/partH-s15/verifier-2026-11-23.log, cited by claim sbs/verifier
 * history in the hand-over.
 *
 * S17 continuation Wave 1 (2026-11-28 sitting, the merged order):
 *   • item 11 (orcads R11): a MISSING RECEIPT NAMES ITSELF — every receipt read is guarded and
 *     returns `missing receipt: <path> (run <cmd>)`; the checker NEVER throws ENOENT. Proved by
 *     deleting a receipt in a throwaway copy: a named RED, never `checker threw`.
 *   • item 1: kind `manifestFacts` — the seal count is read from the GENERATED
 *     manifest-facts.json (regen-manifest.mjs) and re-derived from the live bytes; never a
 *     hardcoded literal (three counts disagreed: 401/385/380).
 *   • item 2: kind `distManifest` — dist-manifest.json (generated by tools/shell-status.mjs) is
 *     joined to the live dist walk AND the prefixes SHELL-STATUS prints; kind `acceptanceCovers`
 *     — the attested tree_sha_end + dist fingerprint must cover the live tree/dist, or the status
 *     must say `COMPLETE at tree X; current tree Y` (a Wave A acceptance cannot certify Wave B).
 *   • item 5: kind `seamCard` — the gate reads the SAME generated seam-card.json the dev chip
 *     reads (W1b); kind `batterySyntax` — every batteries/*.mjs parses (`node --check`) and no
 *     TypeScript token survives in .mjs (the `as const` SyntaxError class that silenced Wave B).
 *   • item 7: kind `pathPortability` — no script resolves its root with `new URL(...).pathname`
 *     (the %20 class), and the spaced-path gate receipt is on record.
 *   • item 12: the offlineTent kind additionally requires the tent receipt to name the
 *     `?dev=1` labelled-DEV run path (the Architect's correction — never a CSV-import claim).
 *
 * Phases:
 *   --phase packaging — the claims that hold MID-COMPOSITE (acceptance-run step 17c, after step
 *   14's reseal and 13d's SHELL-STATUS regen, while ACCEPTANCE-RECEIPTS.txt is still growing).
 *   default (full)    — everything, including the acceptance-derived claims; run after the
 *   composite at the final bytes (its receipt is the close-out's independence evidence).
 *
 * Usage: node scripts/check-claims.mjs [--phase packaging]   (exit 0 = all claims OK)
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PHASE = process.argv.includes('--phase') ? process.argv[process.argv.indexOf('--phase') + 1] : 'full';
const claims = JSON.parse(fs.readFileSync(path.join(ROOT, 'claims.json'), 'utf8'));
let fail = 0, pass = 0, skipped = 0;
const read = (rel) => fs.readFileSync(path.join(ROOT, rel), 'utf8');
const countOf = (txt, re) => (txt.match(re) || []).length;

// item 11 (missing receipt names itself): the ONE guard every receipt/doc read rides. A missing
// or unparseable receipt is a NAMED RED with the regenerating command — never a thrown ENOENT.
const missing = (rel, cmd) => `missing receipt: ${rel} (run ${cmd})`;
const readJson = (rel, cmd) => {
  const p = path.join(ROOT, rel);
  if (!fs.existsSync(p)) return { err: missing(rel, cmd) };
  try { return { j: JSON.parse(fs.readFileSync(p, 'utf8')) }; }
  catch (e) { return { err: `unreadable receipt: ${rel} (${String(e).split('\n')[0].slice(0, 100)}) — the bytes are not the tool's JSON; regenerate with ${cmd}` }; }
};
const readText = (rel, cmd) => {
  const p = path.join(ROOT, rel);
  if (!fs.existsSync(p)) return { err: missing(rel, cmd) };
  return { t: fs.readFileSync(p, 'utf8') };
};
// the dist walk fingerprint — the ONE helper the status, the receipts and the gate share
const distFingerprint = () => {
  const h = createHash('sha256');
  const dir = path.join(ROOT, 'dist');
  const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else h.update(path.relative(ROOT, p) + ':' + createHash('sha256').update(fs.readFileSync(p)).digest('hex') + '\n'); } };
  walk(dir);
  return h.digest('hex');
};
const distFiles = () => {
  const dir = path.join(ROOT, 'dist');
  const out = [];
  const walk = (d) => { for (const e of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, e.name); if (e.isDirectory()) walk(p); else out.push([path.relative(ROOT, p).split(path.sep).join('/'), fs.statSync(p).size, createHash('sha256').update(fs.readFileSync(p)).digest('hex')]); } };
  walk(dir);
  return out.sort((a, b) => a[0].localeCompare(b[0]));
};
// the attest.mjs tree walk, mirrored (scripts/attest.mjs treeSha() — the SAME exclusions)
const attestTreeSha = () => {
  const SKIP = new Set(['node_modules', '.git', '.svelte-kit', 'shots', 'engine-node']);
  const SELF_REF = new Set(['ACCEPTANCE-RECEIPTS.txt', 'CHECKSUMS.txt', 'MANIFEST.txt', 'receipt-attestation.json']);
  const isReceipt = (rel) => rel.startsWith('deliveries/receipts/') || /(^|\/)gate-manifest-[^/]*\.log$/.test(rel);
  const rows = [];
  const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); const rel = path.relative(ROOT, p); if (SKIP.has(f.name)) continue; if (f.isDirectory()) walk(p); else if (SELF_REF.has(f.name) || isReceipt(rel)) continue; else rows.push([rel, createHash('sha256').update(fs.readFileSync(p)).digest('hex')]); } };
  walk(ROOT);
  rows.sort((a, b) => a[0].localeCompare(b[0]));
  const h = createHash('sha256');
  for (const [rel, sha] of rows) h.update(rel + ':' + sha + '\n');
  return h.digest('hex');
};

function check(c) {
  const abs = path.join(ROOT, c.file);
  // the subject read is LAZY and SAFE: kinds like batterySyntax name a DIRECTORY (not a file), and
  // a directory read throws EISDIR — the guard keeps the throw out of the checker (item 11's law:
  // the checker never throws; it returns a named RED or OK).
  const txt = (fs.existsSync(abs) && fs.statSync(abs).isFile()) ? read(c.file) : null;
  switch (c.kind) {
    case 'fileExists':
      return fs.existsSync(abs) ? null : `missing file ${c.file}`;
    case 'regex': {
      if (txt === null) return c.cmd ? missing(c.file, c.cmd) : `missing file ${c.file}`;
      const hit = new RegExp(c.pattern, c.flags || 'm').test(txt);
      return c.negate ? (hit ? `forbidden pattern FOUND: /${c.pattern}/` : null) : (hit ? null : `pattern NOT FOUND: /${c.pattern}/`);
    }
    case 'count': {
      if (txt === null) return c.cmd ? missing(c.file, c.cmd) : `missing file ${c.file}`;
      const n = countOf(txt, new RegExp(c.pattern, c.flags || 'gm'));
      return n === c.expect ? null : `count ${n} ≠ ${c.expect} for /${c.pattern}/`;
    }
    case 'seal': {
      const lines = read(c.file).split('\n').filter((l) => l.trim());
      return lines.length === c.expect ? null : `seal lines ${lines.length} ≠ ${c.expect}`;
    }
    case 'manifestFacts': {
      // item 1 (manifest authority): the seal count comes from the GENERATED facts file and is
      // re-derived from the live bytes — three named numbers, zero literals. A stale facts file
      // (regenerated seal without a regen) REDs naming the drift.
      const facts = readJson('manifest-facts.json', 'node scripts/regen-manifest.mjs');
      if (facts.err) return facts.err;
      const f = facts.j;
      if (typeof f.sealLines !== 'number' || typeof f.contentEntries !== 'number') return 'manifest-facts.json carries no numeric sealLines/contentEntries (regenerate with node scripts/regen-manifest.mjs)';
      const live = read('CHECKSUMS.txt').split('\n').filter((l) => l.trim()).length;
      if (f.sealLines !== live) return `manifest-facts sealLines ${f.sealLines} ≠ live CHECKSUMS.txt lines ${live} — the seal moved after the last regen; re-run the close-out chain`;
      if (f.contentEntries !== live) return `manifest-facts contentEntries ${f.contentEntries} ≠ live content files ${live}`;
      const skippedSidecars = (f.skipped || []).filter((s) => /^SHA256SUMS-.*\.txt$/.test(s));
      const sidecarLive = fs.readdirSync(ROOT).filter((n) => /^SHA256SUMS-.*\.txt$/.test(n));
      const unaccounted = sidecarLive.filter((s) => !skippedSidecars.includes(s));
      if (unaccounted.length) return `sidecar(s) on the tree not named in manifest-facts skipped[]: ${unaccounted.join(', ')}`;
      return null;
    }
    case 'manifestIdentity': {
      const a = read('CHECKSUMS.txt'), b = read('MANIFEST.txt');
      return a === b ? null : 'MANIFEST.txt ≠ CHECKSUMS.txt (the two must stay identical)';
    }
    case 'verifyPackage': {
      let o;
      try { o = execFileSync('node', ['tools/verify-package.mjs', '.'], { cwd: ROOT, encoding: 'utf8' }); }
      catch (e) { return `verify-package exit ≠ 0: ${String((e.stdout || '') + (e.stderr || e)).split('\n')[0].slice(0, 140)}`; }
      const m = o.match(/verify-package: (\d+) OK \/ (\d+) FAILED \/ (\d+) missing/);
      if (!m) return `unparseable verify output: ${o.split('\n')[0].slice(0, 120)}`;
      if (+m[2] !== 0 || +m[3] !== 0) return `verify FAILED=${m[2]} missing=${m[3]} (expect 0/0)`;
      const sealLines = read('CHECKSUMS.txt').split('\n').filter((l) => l.trim()).length;
      if (+m[1] !== sealLines) return `verify OK ${m[1]} ≠ seal lines ${sealLines} (the converse-consistent seal)`;
      if (!/converse clean/.test(o)) return 'converse check line missing from verify output';
      return null;
    }
    case 'distManifest': {
      // item 2 (dist identity): the GENERATED dist-manifest.json is joined to (a) the live dist
      // walk — byte for byte — and (b) the prefixes SHELL-STATUS.md prints. A stale status hash
      // or a stale manifest REDs naming the drifted file.
      const man = readJson('dist-manifest.json', 'node tools/shell-status.mjs');
      if (man.err) return man.err;
      const listed = man.j.files || [];
      if (!Array.isArray(listed) || !listed.length) return 'dist-manifest.json carries no files[] (regenerate with node tools/shell-status.mjs)';
      const live = distFiles();
      const det = [];
      if (listed.length !== live.length) det.push(`dist-manifest files ${listed.length} ≠ live dist files ${live.length}`);
      const byName = new Map(live.map(([rel, bytes, sha]) => [rel, [bytes, sha]]));
      for (const e of listed) {
        const lv = byName.get(e.file);
        if (!lv) { det.push(`dist-manifest names ${e.file} — absent from the live dist walk`); continue; }
        if (lv[1] !== e.sha256) det.push(`dist ${e.file}: manifest sha ${String(e.sha256).slice(0, 12)}… ≠ live ${lv[1].slice(0, 12)}…`);
        if (lv[0] !== e.bytes) det.push(`dist ${e.file}: manifest size ${e.bytes} ≠ live ${lv[0]}`);
      }
      if (man.j.distFingerprint && man.j.distFingerprint !== distFingerprint()) det.push('dist-manifest distFingerprint ≠ the live dist walk');
      const status = readText(c.file || 'SHELL-STATUS.md', 'node tools/shell-status.mjs');
      if (status.err) return status.err;
      for (const e of listed) {
        const pre = String(e.sha256).slice(0, 16);
        if (!status.t.includes(pre)) return `dist ${e.file} prefix ${pre}… absent from ${c.file || 'SHELL-STATUS.md'} — the status no longer renders the dist manifest`;
      }
      return det.length ? det.join('; ') : null;
    }
    case 'acceptanceCovers': {
      // item 2 (acceptance-covers-this-tree): the attested tree_sha_end + dist fingerprint must
      // equal the live tree/dist — or the generated status must carry the honest
      // `COMPLETE at tree X; current tree Y` line. Either leg passes; a lying status fails.
      const att = readJson('receipt-attestation.json', 'bash scripts/acceptance-run.sh (the composite; attest finish seals it)');
      if (att.err) return att.err;
      const last = (att.j.runs || [])[((att.j.runs || []).length) - 1];
      if (!last) return 'receipt-attestation.json holds no run record';
      const liveTree = attestTreeSha();
      const treeCovered = last.tree_sha_end === liveTree;
      const liveDist = fs.existsSync(path.join(ROOT, 'dist')) ? distFingerprint() : null;
      const distCovered = !!last.dist_sha && !!liveDist && last.dist_sha === liveDist;
      if (treeCovered && distCovered) return null;
      const status = readText(c.file || 'SHELL-STATUS.md', 'node tools/shell-status.mjs');
      if (status.err) return status.err;
      const line = (status.t.match(/^- acceptance-covers-this-tree: .*$/m) || [])[0] || '';
      if (!line) return 'SHELL-STATUS carries no `- acceptance-covers-this-tree:` line — the coverage cannot be read as either covered or honestly moved';
      const treeMoved = treeCovered || (last.tree_sha_end && line.includes(`COMPLETE at tree ${last.tree_sha_end.slice(0, 16)}`) && line.includes(`current tree ${liveTree.slice(0, 16)}`));
      if (!treeMoved) return `the attestation does not cover this tree (attested ${String(last.tree_sha_end).slice(0, 12)}… vs live ${liveTree.slice(0, 12)}…) and the status line does not carry the honest tree-move wording: ${line}`;
      if (!distCovered && !/dist fingerprint is NOT covered|no dist fingerprint/.test(line)) return `the acceptance dist fingerprint does not cover the live dist and the status line does not say so: ${line}`;
      return null;
    }
    case 'distPrefix': {
      const status = read(c.file);
      for (const rel of c.files) {
        const p = path.join(ROOT, rel);
        if (!fs.existsSync(p)) return `missing dist file ${rel}`;
        const pre = createHash('sha256').update(fs.readFileSync(p)).digest('hex').slice(0, 16);
        if (!status.includes(pre)) return `dist ${rel} prefix ${pre}… absent from ${c.file}`;
      }
      return null;
    }
    case 'sideBySide': {
      const j = readJson(c.file, 'node scripts/side-by-side-s15.mjs');
      if (j.err) return j.err;
      const doc = readText('deliveries/S15-SIDE-BY-SIDE-2026-11-21.md', 'node scripts/side-by-side-s15.mjs');
      if (doc.err) return doc.err;
      const jj = j.j;
      const caps = jj.captures || [];
      const fails = (jj.verdicts || []).filter((v) => v.checks && Object.values(v.checks).some((x) => x === false));
      const fb = caps.filter((x) => x.fallback);
      const det = [];
      if ((jj.matrix ? jj.matrix.complete : false) !== true) det.push(`matrix incomplete: missing ${((jj.matrix || {}).missing || []).join(', ')}`);
      if (caps.length !== c.expectCaptures) det.push(`captures ${caps.length} ≠ ${c.expectCaptures}`);
      if (fb.length !== (c.expectFallback ?? 0)) det.push(`fallback captures ${fb.length} ≠ ${c.expectFallback ?? 0}`);
      if (fails.length) det.push(`${fails.length} right-verdict FAIL row(s): ${fails.map((v) => `${v.scene} ${v.w}x${v.h} ${v.theme}`).join(', ')}`);
      const docFb = countOf(doc.t, /^\| [^|]*\*\*FALLBACK — NOT the intended scene\*\*/gm);   // table CELLS only — the header prose mentions the mechanism by name
      if (docFb !== fb.length) det.push(`doc fallback cells ${docFb} ≠ receipt fallback ${fb.length}`);
      return det.length ? det.join('; ') : null;
    }
    case 'statusAcceptance': {
      // the S17 A4 work order's kind, verbatim semantics: the SHELL-STATUS acceptance line must
      // agree with the TERMINAL MARKER the acceptance script actually wrote — never the reverse.
      const acc = readText(c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt', 'bash scripts/acceptance-run.sh');
      if (acc.err) return acc.err;
      const status = readText(c.file || 'SHELL-STATUS.md', 'node tools/shell-status.mjs');
      if (status.err) return status.err;
      const wantsComplete = c.expect === 'complete';
      const hasComplete = /ACCEPTANCE RUN COMPLETE — every step exit 0/.test(acc.t);
      const line = (status.t.match(/^- acceptance run: .*$/m) || [])[0] || '';
      if (hasComplete !== wantsComplete) return `acceptance marker ${hasComplete ? 'present' : 'absent'} ≠ expect ${c.expect}`;
      if (wantsComplete ? !/COMPLETE/.test(line) : !/no COMPLETE marker/.test(line))
        return `SHELL-STATUS line disagrees with the receipt: ${line || '(missing)'}`;
      return null;
    }
    case 'statusAgreement': {
      const acc = readText(c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt', 'bash scripts/acceptance-run.sh');
      if (acc.err) return acc.err;
      const status = readText(c.file || 'SHELL-STATUS.md', 'node tools/shell-status.mjs');
      if (status.err) return status.err;
      const hasComplete = /ACCEPTANCE RUN COMPLETE — every step exit 0/.test(acc.t);
      const line = (status.t.match(/^- acceptance run: .*$/m) || [])[0] || '';
      if (!line) return 'SHELL-STATUS carries no `- acceptance run:` line';
      if (hasComplete && !/COMPLETE/.test(line)) return `receipt says COMPLETE but the status line does not: ${line}`;
      if (!hasComplete && /the acceptance run of record is COMPLETE/.test(line)) return `CONTRADICTORY COMPLETE line while the receipt holds no COMPLETE marker: ${line}`;
      return null;
    }
    case 'statusFreshness': {
      // the S17 A4 work order's kind + item 2's join: each named receipt's distHash decides the
      // content verdict AND the verdict is joined to the GENERATED dist-manifest.json — the
      // manifest, the receipts and the live directory must all agree, or the drift is named.
      const status = readText(c.file || 'SHELL-STATUS.md', 'node tools/shell-status.mjs');
      if (status.err) return status.err;
      const man = readJson('dist-manifest.json', 'node tools/shell-status.mjs');
      if (man.err) return man.err;
      const now = distFingerprint();
      if (man.j.distFingerprint !== now) return `dist-manifest.json distFingerprint ≠ the live dist walk — the manifest is stale; re-run node tools/shell-status.mjs`;
      for (const [receipt, label] of c.receipts) {
        const j = readJson(receipt, c.cmd || 'the owning battery (see claims.json cmd)');
        if (j.err) return j.err;
        if (!j.j.distHash) return `${receipt} has no distHash (T1 receipt format missing)`;
        const want = j.j.distHash === now ? 'content FRESH' : 'content STALE';
        const line = status.t.split('\n').find((l) => l.startsWith(`- ${label}:`)) || '';
        if (!line.includes(want)) return `${label} says "${line || '(missing)'}" but the bytes say ${want}`;
      }
      return null;
    }
    case 'sideBySideNonVacuity': {
      const j = readJson(c.file, 'node scripts/side-by-side-s15.mjs');
      if (j.err) return j.err;
      const jj = j.j;
      const caps = jj.captures || [];
      const nvs = jj.nonVacuity || [];
      const key = (r) => `${r.side}|${r.scene}|${r.w}|${r.h}|${r.theme}`;
      const byKey = new Map(nvs.map((r) => [key(r), r]));
      const bad = [];
      if (nvs.length !== caps.length) bad.push(`nonVacuity records ${nvs.length} ≠ captures ${caps.length}`);
      for (const cap of caps) {
        const nv = byKey.get(key(cap));
        if (!nv) { bad.push(`${key(cap)}: no nonVacuity twin`); continue; }
        if (nv.met !== true) bad.push(`${key(cap)}: met=${JSON.stringify(nv.met)} (must be exactly true)`);
        if (nv.expected !== cap.expected) bad.push(`${key(cap)}: expected marker text differs between capture and nonVacuity`);
      }
      return bad.length ? bad.join('; ') : null;
    }
    case 'attestation': {
      const raw = readJson(c.file || 'receipt-attestation.json', 'bash scripts/acceptance-run.sh');
      if (raw.err) return raw.err;
      const acc = readText(c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt', 'bash scripts/acceptance-run.sh');
      if (acc.err) return acc.err;
      const recs = Array.isArray(raw.j) ? raw.j : raw.j.runs || [];
      const last = recs[recs.length - 1];
      if (!last) return 'receipt-attestation.json holds no run record';
      if (last.complete !== true) return `the last run record is not COMPLETE (complete=${JSON.stringify(last.complete)}${last.stoppedAt ? ', stoppedAt ' + last.stoppedAt : ''})`;
      const got = createHash('sha256').update(fs.readFileSync(path.join(ROOT, c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt'))).digest('hex');
      if (last.log_sha256 !== got) return `log_sha256 mismatch: attestation ${last.log_sha256} vs ACCEPTANCE-RECEIPTS.txt ${got} — the receipt changed after the run closed (or the attestation is stale)`;
      const exits = last.per_step_exit_codes || [];
      if (!exits.length || exits.some((x) => x !== 0)) return `per_step_exit_codes not all 0: [${exits.join(', ')}]`;
      if (!last.tree_sha_start || !last.tree_sha_end) return 'tree_sha_start/tree_sha_end missing from the run record';
      if (!/ACCEPTANCE RUN COMPLETE — every step exit 0/.test(acc.t)) return 'the receipt of record carries no COMPLETE terminal marker';
      return null;
    }
    case 'freshnessMap': {
      const map = readJson(c.file || 'freshness.json', 'node scripts/gen-freshness.mjs');
      if (map.err) return map.err;
      const acc = readText(c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt', 'bash scripts/acceptance-run.sh');
      if (acc.err) return acc.err;
      const det = [];
      for (const [gen, rec] of Object.entries(map.j.files || {})) {
        for (const [inp, want] of Object.entries(rec.inputs || {})) {
          const p = path.join(ROOT, inp);
          if (!fs.existsSync(p)) { det.push(`${gen}: input missing ${inp}`); continue; }
          const got = createHash('sha256').update(fs.readFileSync(p)).digest('hex');
          if (got !== want) det.push(`${gen}: input ${inp} CHANGED (recorded ${want.slice(0, 16)}…, now ${got.slice(0, 16)}…) — regenerate freshness.json`);
        }
        if (rec.acceptanceSha) {
          const got = createHash('sha256').update(fs.readFileSync(path.join(ROOT, c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt'))).digest('hex');
          if (rec.acceptanceSha !== got) det.push(`${gen}: acceptanceSha ${rec.acceptanceSha.slice(0, 16)}… ≠ live ACCEPTANCE-RECEIPTS.txt ${got.slice(0, 16)}…`);
        }
      }
      if (map.j.acceptanceSha) {
        const got = createHash('sha256').update(fs.readFileSync(path.join(ROOT, c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt'))).digest('hex');
        if (map.j.acceptanceSha !== got) det.push(`freshness.json: acceptanceSha ≠ live ACCEPTANCE-RECEIPTS.txt`);
      }
      const status = readText(c.file2 || 'SHELL-STATUS.md', 'node tools/shell-status.mjs');
      if (status.err) return status.err;
      const m = status.t.match(/- acceptance receipt sha256 \(acceptanceSha\): ([0-9a-f]{64})/);
      const live = createHash('sha256').update(fs.readFileSync(path.join(ROOT, c.acceptanceFile || 'ACCEPTANCE-RECEIPTS.txt'))).digest('hex');
      if (!m) det.push('SHELL-STATUS.md prints no acceptanceSha line');
      else if (m[1] !== live) det.push(`SHELL-STATUS acceptanceSha ${m[1].slice(0, 16)}… ≠ live receipt ${live.slice(0, 16)}…`);
      return det.length ? det.join('; ') : null;
    }
    case 'offlineTent': {
      // the Wave B #4 tent gate + item 12: the receipt's own numbers are the law — zero external
      // requests, the boot/restore loop completed, the dist fingerprint present, and the run
      // PATH is the ?dev=1 labelled-DEV boot (the Architect's T6 correction — a CSV-import path
      // claim is void). A planted remote font URL makes the battery DIE NAMING THE URL.
      const j = readJson(c.file || 'deliveries/receipts/offline-tent.json', 'npm run battery:offline');
      if (j.err) return j.err;
      const jj = j.j;
      const ext = jj.externalRequests || [];
      if (ext.length) return `the tent leaked: ${ext.length} external request(s) — ${ext.slice(0, 3).join(' | ')}`;
      if (jj.booted !== true || jj.drafted !== true || jj.restored !== true) return `the draft turn broke under the tent: booted=${jj.booted} drafted=${jj.drafted} restored=${jj.restored}`;
      if (!jj.distHash) return 'the tent receipt carries no distHash (the bytes it pinned are unrecorded)';
      if (jj.labelledDev !== true) return `the tent receipt does not name the ?dev=1 labelled-DEV run path (labelledDev=${JSON.stringify(jj.labelledDev ?? null)}) — the Architect's contract runs the tent on the DEV boot, never a CSV-import path`;
      return null;
    }
    case 'seamCard': {
      // item 5 W1b (HY4's exact law): the gate reads the SAME generated card the dev chip reads —
      // the pin must match SNAPSHOT.md and the seal count the live CHECKSUMS.txt lines. Never a
      // hardcoded pin or count.
      const card = readJson('seam-card.json', 'node --import ./scripts/node-port-register.mjs scripts/gen-seam-card.mjs');
      if (card.err) return card.err;
      const snap = readText('SNAPSHOT.md', '(the contract of record — part of the package)');
      if (snap.err) return snap.err;
      const pin = (snap.t.match(/Engine commit: `([0-9a-f]{8,9})`/) || [])[1];
      return card.j.pin === pin && card.j.sealCount === read('CHECKSUMS.txt').split('\n').filter((l) => l.trim()).length
        ? null
        : 'seam-card pin/count disagrees with SNAPSHOT/seal';
    }
    case 'batterySyntax': {
      // item 5 (HY4 N5): every batteries/*.mjs parses under node --check and no TypeScript token
      // survives in .mjs — the `as const` SyntaxError class that silenced the Wave B battery.
      let o;
      try { o = execFileSync('node', ['scripts/gate-battery-syntax.mjs'], { cwd: ROOT, encoding: 'utf8' }); }
      catch (e) { return `battery syntax gate failed: ${String((e.stdout || '') + (e.stderr || '')).split('\n').filter((l) => /FAIL|TS-ISM/.test(l)).slice(0, 3).join(' | ') || 'exit nonzero'}`; }
      if (!/gate-battery-syntax: PASS/.test(o)) return `battery syntax gate did not PASS: ${o.split('\n').slice(-1)[0]}`;
      return null;
    }
    case 'pathPortability': {
      // item 7 (DS N7 / Porca): the gates must run from a path containing a space — the defect
      // class is `new URL(...).pathname` yielding %20. Two legs: (a) no script/tool/battery still
      // resolves a ROOT through `.pathname` (the offender is named); (b) the spaced-path gate
      // receipt is on record and says PASS with the spaced root named.
      const offenders = [];
      for (const dir of ['scripts', 'tools', 'batteries']) {
        const d = path.join(ROOT, dir);
        if (!fs.existsSync(d)) continue;
        for (const f of fs.readdirSync(d).filter((x) => x.endsWith('.mjs'))) {
          const txt = fs.readFileSync(path.join(d, f), 'utf8');
          txt.split('\n').forEach((l, i) => {
            const t = l.trim();
            if (t.startsWith('//') || t.startsWith('*') || t.startsWith('/*')) return;   // comments may NAME the defect class — they are not code
            const code = l.replace(/'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|`(?:[^`\\]|\\.)*`/g, "''");
            if (/new URL\((?:'[^']*'|"[^"]*"|[^)]*)\)\.pathname/.test(code)) offenders.push(`${dir}/${f}:${i + 1}: ${t.slice(0, 110)}`);
          });
        }
      }
      if (offenders.length) return `spaced-path defect class alive (new URL(...).pathname): ${offenders.slice(0, 3).join(' | ')}`;
      const log = readText('deliveries/receipts/path-portability.log', 'node scripts/verify-spaced-path.mjs');
      if (log.err) return log.err;
      if (!/SPACED-PATH GATE: PASS/.test(log.t)) return `the spaced-path gate receipt does not say PASS — ${log.t.split('\n').filter((l) => l.trim()).slice(-3).join(' | ').slice(0, 200)}`;
      if (!/(%20|\s)/.test(log.t.split('\n').find((l) => /spaced root:/i.test(l)) || '')) return 'the spaced-path receipt names no spaced root (the run path is unproven)';
      return null;
    }
    case 'stateBlocks': {
      // the S17 A3 gate: the generated state blocks (README top block, ZAI.md, the hand-over state
      // paragraph) must equal what gen-state-block.mjs produces from the CURRENT claim results —
      // green prose becomes impossible while a claim is RED, because the block itself shows RED.
      try {
        execFileSync('node', ['scripts/gen-state-block.mjs', '--check'], { cwd: ROOT, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] });
        return null;
      } catch (e) {
        const o = String((e.stdout || '') + (e.stderr || ''));
        return o.trim().split('\n').filter(Boolean).slice(0, 3).join(' | ') || 'gen-state-block --check failed';
      }
    }
    default:
      return `unknown claim kind ${c.kind}`;
  }
}

