/* regen-manifest.mjs — regenerate CHECKSUMS.txt (sha256 of every non-excluded file) + MANIFEST.txt.
 * The D4 fix: dist/ is NO LONGER skipped — the build output is hashed and listed like any other
 * file (the gate once verified 233 source hashes while the package could not boot).
 * ACCEPTANCE-RECEIPTS.txt is excluded: it is the meta-layer (self-referential by design, like
 * MANIFEST.txt/CHECKSUMS.txt) — acceptance-run.sh appends receipt lines AFTER regen, so hashing it
 * here would guarantee a hash drift at the gate. Caught by the runner itself, 2026-11-17.
 * The cakepanz-7 fix (mirrors gate-manifest.mjs): the receipt layer joins the same exclusion —
 * deliveries/receipts/ and any gate-manifest-*.log are unlisted here, so a receipt written at the
 * final state can never fail the next regen/gate roundtrip (a receipt is the raw stdout of the
 * tool at the final state; if the state changes, the receipt is rewritten). */
import fs from 'node:fs';
import { fileURLToPath } from 'node:url'; import path from 'node:path'; import crypto from 'node:crypto';
const TREE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');   // spaced-path portability (item 7): fileURLToPath semantics without the %20 pathname bug
const SKIP = new Set(['node_modules', '.git', '.svelte-kit', 'shots', 'engine-node']);
// item 1 (manifest authority — Pickle D1 / DS N9 / orcads R12 / HY4 D1): a checksum file cannot
// seal itself, and the seal rule must be a NAMED RULE, not a dated literal. SELF_REF is the
// self-referential meta layer (a file cannot contain its own digest); any SHA256SUMS-*.txt
// sidecar is TRANSPORT metadata (it describes the delivery zip, not product content — item 6).
// One predicate, used by the walk, exported nowhere: the regen/gate/verify trio share the rule.
const SELF_REF = new Set(['ACCEPTANCE-RECEIPTS.txt', 'CHECKSUMS.txt', 'MANIFEST.txt']); // cakepanz-6 fix: the two self-listing lines made the sha256 roundtrip impossible to converge (each regen's self-hash described the previous bytes — caught by this sitting's packaging roundtrip; the gate already skipped them as self-referential by design)
const isManifestMeta = (rel) => SELF_REF.has(rel) || /^SHA256SUMS-.*\.txt$/.test(rel);
const isReceipt = (rel) => rel.startsWith('deliveries/receipts/') || /(^|\/)gate-manifest-[^/]*\.log$/.test(rel);   // cakepanz-7: the receipt layer joins the self-reference exclusion
const rows = [];
const skipped = [];
const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); const rel = path.relative(TREE, p); if (SKIP.has(f.name)) continue; if (f.isDirectory()) walk(p); else if (isManifestMeta(rel) || isReceipt(rel)) { skipped.push(rel); continue; } else rows.push([crypto.createHash('sha256').update(fs.readFileSync(p)).digest('hex'), rel]); } };
walk(TREE);
rows.sort((a, b) => a[1].localeCompare(b[1]));
fs.writeFileSync(path.join(TREE, 'CHECKSUMS.txt'), rows.map(([h, r]) => `${h}  ${r}`).join('\n') + '\n');
fs.writeFileSync(path.join(TREE, 'MANIFEST.txt'), rows.map(([h, r]) => `${h}  ${r}`).join('\n') + '\n');
// item 1: ONE manifest-facts.json — the counts' single source of truth. sealLines is the number of
// lines CHECKSUMS.txt now carries (= verify-package's OK count on a clean tree); contentEntries is
// the number of hashed content files; skipped[] names every excluded path (the meta layer + the
// transport sidecars + the receipt layer) so the exclusions are auditable. Never hardcode a count:
// claims.json's seal-count claim reads THIS file and re-derives the live number from the bytes.
const sumsRel = fs.readdirSync(TREE).map((n) => /^SHA256SUMS-.*\.txt$/.test(n) ? n : null).filter(Boolean).sort();
const facts = {
  meta: 'GENERATED by scripts/regen-manifest.mjs — do not edit; regenerated at every reseal. sealLines == CHECKSUMS.txt line count == verify-package OK on a clean tree; contentEntries == hashed content files; skipped[] is the named meta/transport/receipt exclusion layer.',
  generator: 'node scripts/regen-manifest.mjs',
  generatedOver: null,
  sealLines: rows.length,
  contentEntries: rows.length,
  skipped: skipped.sort(),
  sha256sumsLines: sumsRel.reduce((n, s) => n + fs.readFileSync(path.join(TREE, s), 'utf8').split('\n').filter((l) => l.trim()).length, 0),
  sha256sumsFiles: sumsRel,
  sha256sumsSha: sumsRel.map((s) => crypto.createHash('sha256').update(fs.readFileSync(path.join(TREE, s))).digest('hex')),
};
try { facts.generatedOver = JSON.parse(fs.readFileSync(path.join(TREE, 'receipt-attestation.json'), 'utf8')).runs?.at(-1)?.log_sha256 ?? null; } catch { facts.generatedOver = null; }
fs.writeFileSync(path.join(TREE, 'manifest-facts.json'), JSON.stringify(facts, null, 1) + '\n');
console.log(`regen: ${rows.length} entries (seal lines ${facts.sealLines}, skipped ${skipped.length}: ${sumsRel.join(', ') || 'no sidecar'})`);
