#!/usr/bin/env node
/* tint-scope-measure.mjs — item 9 (orcads R8 / HY4 W8): the takeover tint scope is DEFERRED —
 * the Owner picks between chip/border-only and gold→paper ink. This script MEASURES all 32 teams
 * in LIGHT mode under BOTH scopes and files both tables; it decides nothing.
 *
 *   Scope A — chip/border-only: the tint paints only a chip/border (no text rides the tinted
 *             surface). The measured pair is the tint against its ADJACENT surfaces (the panel
 *             it sits on, and the gold it borders) — WCAG 1.4.11 non-text contrast (≥3:1) is the
 *             bar recorded, per team.
 *   Scope B — gold→paper ink: the gold ink moves ONTO the tinted surface (the tint becomes the
 *             paper under the gold text). The measured pair is tint vs the mode's gold ink —
 *             WCAG AA text (≥4.5:1) is the bar recorded, per team, before vs after the tint.
 *
 * The measured tint is the SHIPPED tintOf() (the item-9 repair: 12% in, halve while the gold's
 * contrast degrades, fall back to the panel). Run:
 *   node --import ./scripts/node-port-register.mjs scripts/tint-scope-measure.mjs
 * Output: deliveries/receipts/tint-scope-measure.json + deliveries/TINT-SCOPE-MEASURE-2026-11-28.md
 * (both GENERATED — never hand-edited). Exit 0 always: this is a MEASUREMENT, not a gate.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const port = await import(path.join(ROOT, 'src/lib/port/takeover.ts'));
const tokens = await import(path.join(ROOT, 'src/lib/port/tokens.ts'));

const AA_TEXT = 4.5;
const AA_NONTEXT = 3;
const rows = [];
for (const team of Object.keys(tokens.ZPB_TEAM_COLORS)) {
  const light = port.tintReceipt().rows.find((r) => r.team === team)?.light ?? null;
  if (!light) { rows.push({ team, error: 'no receipt row' }); continue; }
  const tint = light.tint, panel = tokens.PANEL_HEX_LIGHT;
  // the gold ink of light mode — the SAME export the takeover module pairs with (one source)
  const goldInk = port.GOLD_OF.light;
  const panelGoldBefore = port.contrastOf(panel, goldInk);
  const tintGoldAfter = port.contrastOf(tint, goldInk);
  rows.push({
    team,
    panel,
    goldInk,
    tint,
    scopeA: {   // chip/border-only: the tinted surface vs what it touches
      tintVsPanel: Number(port.contrastOf(tint, panel).toFixed(2)),
      tintVsGold: Number(port.contrastOf(tint, goldInk).toFixed(2)),
      nonTextBar: AA_NONTEXT,
      nonTextPassTintVsPanel: port.contrastOf(tint, panel) >= AA_NONTEXT,
    },
    scopeB: {   // gold→paper ink: the gold text ON the tinted surface
      beforePanelGold: Number(panelGoldBefore.toFixed(2)),
      afterTintGold: Number(tintGoldAfter.toFixed(2)),
      aaTextBar: AA_TEXT,
      aaPass: tintGoldAfter >= AA_TEXT,
      noRegression: tintGoldAfter >= panelGoldBefore,
      degraded: tintGoldAfter < panelGoldBefore,
    },
  });
}

const receipt = {
  meta: 'GENERATED by scripts/tint-scope-measure.mjs — item 9: BOTH tint scopes measured for all 32 teams in LIGHT mode; the scope is the OWNER\'s decision and is NOT picked here. The measured tint is the shipped tintOf() (12% in, halve while the gold\'s contrast degrades, fall back to the panel) over the imported tokens (PANEL_HEX_LIGHT, LIGHT.gold3).',
  generatedOver: (() => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, 'receipt-attestation.json'), 'utf8')).runs?.at(-1)?.log_sha256 ?? null; } catch { return null; } })(),
  mode: 'light',
  teams: rows.length,
  scopes: { A: 'chip/border-only — tint vs panel (WCAG 1.4.11 non-text, 3:1 recorded per team)', B: 'gold→paper ink — gold text on the tinted surface (WCAG AA text, 4.5:1; before vs after)' },
  rows,
  summary: {
    scopeA_tintVsPanel_below3: rows.filter((r) => r.scopeA && !r.scopeA.nonTextPassTintVsPanel).map((r) => r.team),
    scopeB_aaFail: rows.filter((r) => r.scopeB && !r.scopeB.aaPass).map((r) => r.team),
    scopeB_regressions: rows.filter((r) => r.scopeB && r.scopeB.degraded).map((r) => r.team),
  },
};
fs.mkdirSync(path.join(ROOT, 'deliveries', 'receipts'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'deliveries', 'receipts', 'tint-scope-measure.json'), JSON.stringify(receipt, null, 1) + '\n');

// the two tables, markdown — the Owner's reading copy
const md = [];
md.push('# TINT SCOPE MEASUREMENT — both scopes, 32 teams, LIGHT mode (GENERATED — the scope is NOT picked)');
md.push('');
md.push(`Item 9 (orcads R8 / HY4 W8): the takeover tint scope is **DEFERRED — the Owner picks**. Both measured tables are filed here; the fix that landed (either scope keeps it) is the named repair in \`src/lib/port/takeover.ts:tintOf()\` — start the 12% mix, halve the ratio while the mix degrades the gold's contrast against the plain panel, fall back to the panel. Panel and gold are IMPORTED from \`tokens.ts\` (\`PANEL_HEX_LIGHT\` = ${tokens.PANEL_HEX_LIGHT}, light gold ink \`LIGHT.gold3\` = ${tokens.LIGHT.gold3}) — no copied colour literals, and the receipt measures the same surface the tint draws on.`);
md.push('');
md.push(`Regressions after the repair: **${receipt.summary.scopeB_regressions.length || 'zero'}** team(s) degrade the gold's contrast in light mode (before the repair the dark primaries — Arizona first — degraded; the halving loop now walks them back to the panel).`);
md.push('');
md.push('## Scope A — chip/border-only (tint vs panel; WCAG 1.4.11 non-text bar 3:1)');
md.push('');
md.push('| team | panel | tint | tint vs panel | ≥3:1 | tint vs gold |');
md.push('|---|---|---|---|---|---|');
for (const r of rows) md.push(`| ${r.team} | ${r.panel} | ${r.tint} | ${r.scopeA.tintVsPanel} | ${r.scopeA.nonTextPassTintVsPanel ? 'PASS' : 'FAIL'} | ${r.scopeA.tintVsGold} |`);
md.push('');
md.push('## Scope B — gold→paper ink (gold text ON the tinted surface; WCAG AA text bar 4.5:1)');
md.push('');
md.push('| team | panel+gold (before) | tint+gold (after) | AA 4.5:1 | regression |');
md.push('|---|---|---|---|---|');
for (const r of rows) md.push(`| ${r.team} | ${r.scopeB.beforePanelGold} | ${r.scopeB.afterTintGold} | ${r.scopeB.aaPass ? 'PASS' : 'FAIL'} | ${r.scopeB.degraded ? 'YES' : 'no'} |`);
md.push('');
md.push('## The decision this table serves (NOT made here)');
md.push('');
md.push('- Scope A keeps the tint as decoration only: no text ever rides the tinted surface; the bar is non-text contrast against the panel.');
md.push('- Scope B moves the gold ink onto the tinted surface: the bar is AA text contrast, and the delivered bytes\' defect (dark primaries — Arizona Cardinals first — pulled the gold below the before-contrast) is the regression the halving repair kills.');
md.push('- The Owner picks one scope; the full-scope fix is then built to THAT bar. Nothing here weakens waveB W8 (contrast never degrades, after ≥ before, both modes).');
fs.writeFileSync(path.join(ROOT, 'deliveries', 'TINT-SCOPE-MEASURE-2026-11-28.md'), md.join('\n') + '\n');
console.log(`tint-scope-measure: ${rows.length} teams measured in light mode under BOTH scopes`);
console.log(`  scopeA tintVsPanel below 3:1: ${receipt.summary.scopeA_tintVsPanel_below3.length ? receipt.summary.scopeA_tintVsPanel_below3.join(', ') : 'none'}`);
console.log(`  scopeB AA fails (post-repair): ${receipt.summary.scopeB_aaFail.length ? receipt.summary.scopeB_aaFail.join(', ') : 'none'}`);
console.log(`  scopeB regressions (post-repair): ${receipt.summary.scopeB_regressions.length ? receipt.summary.scopeB_regressions.join(', ') : 'none'}`);
console.log('  filed: deliveries/receipts/tint-scope-measure.json + deliveries/TINT-SCOPE-MEASURE-2026-11-28.md');
