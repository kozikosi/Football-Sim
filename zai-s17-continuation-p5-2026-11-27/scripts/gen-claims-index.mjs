#!/usr/bin/env node
/* gen-claims-index.mjs — the Wave B #10 claims index (the fresh Verifier's one page): every claim
 * in claims.json rendered as CLAIM → COMMAND → EXPECTED STDOUT SHAPE → EXIT CODE. The order §3.10
 * asks for exactly this; the T2 protocol already made every claim machine-checkable — this page
 * makes the check RUNNABLE from one place without reading the checker's source.
 *
 * Run: node scripts/gen-claims-index.mjs
 * Output: deliveries/CLAIMS-INDEX.md (GENERATED — regenerated at the final bytes; the receipt law)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const claims = JSON.parse(fs.readFileSync(path.join(ROOT, 'claims.json'), 'utf8'));

const KIND_CMD = {
  fileExists: { cmd: 'node scripts/check-claims.mjs [--phase packaging]', expect: 'OK [id] ... · exit 0 (a missing file REDs naming it)', exit: '0 (green) / 1 (any RED)' },
  regex: { cmd: 'node scripts/check-claims.mjs', expect: 'the pattern matched (or, for negate, NOT matched) in the named file', exit: '0 / 1' },
  count: { cmd: 'node scripts/check-claims.mjs', expect: 'the count equals expect', exit: '0 / 1' },
  seal: { cmd: 'node scripts/check-claims.mjs', expect: 'CHECKSUMS.txt line count equals expect', exit: '0 / 1' },
  manifestIdentity: { cmd: 'node scripts/check-claims.mjs', expect: 'MANIFEST.txt byte-identical to CHECKSUMS.txt', exit: '0 / 1' },
  verifyPackage: { cmd: 'node tools/verify-package.mjs .', expect: 'verify-package: N OK / 0 FAILED / 0 missing + converse clean, N == seal lines', exit: '0 (green) / 1 (any FAILED/missing/EXTRA)' },
  distPrefix: { cmd: 'node scripts/check-claims.mjs', expect: "each dist file's sha256 prefix equals what SHELL-STATUS.md prints", exit: '0 / 1' },
  sideBySide: { cmd: 'node scripts/check-claims.mjs (receipt: node scripts/side-by-side-s15.mjs)', expect: '41 captures · matrix COMPLETE · 0 fallbacks · 0 verdict FAILs', exit: '0 / 1' },
  sideBySideNonVacuity: { cmd: 'node scripts/check-claims.mjs', expect: '41 captures join 1:1 to 41 nonVacuity records, every met === true', exit: '0 / 1' },
  statusAcceptance: { cmd: 'node scripts/check-claims.mjs', expect: 'the SHELL-STATUS acceptance line agrees with the receipt terminal marker + expect', exit: '0 / 1' },
  statusAgreement: { cmd: 'node scripts/check-claims.mjs --phase packaging', expect: 'status line and receipt marker agree in BOTH directions (no contradictory COMPLETE)', exit: '0 / 1' },
  statusFreshness: { cmd: 'node scripts/check-claims.mjs', expect: 'receipt distHash vs shipped dist says FRESH and the status line carries it', exit: '0 / 1' },
  attestation: { cmd: 'node scripts/check-claims.mjs', expect: 'receipt-attestation.json last record COMPLETE, log_sha256 == sha256(ACCEPTANCE-RECEIPTS.txt), all exits 0', exit: '0 / 1' },
  freshnessMap: { cmd: 'node scripts/gen-freshness.mjs (regen) + node scripts/check-claims.mjs (verify)', expect: 'every recorded input hash equals the live bytes; acceptanceSha matches the receipt AND the status line', exit: '0 / 1' },
  stateBlocks: { cmd: 'node scripts/gen-state-block.mjs --check', expect: 'the three generated state blocks equal the current claim results', exit: '0 (current) / 1 (drift, doc named)' },
};

// item 3 (fixed point): the index is DETERMINISTIC — the header stamps the receipt-of-record's
// content hash, not the clock, so two regenerations over the same state are byte-identical and
// the close-out seal can converge.
const sealedOver = (() => { try { return JSON.parse(fs.readFileSync(path.join(ROOT, 'receipt-attestation.json'), 'utf8')).runs?.at(-1)?.log_sha256 ?? null; } catch { return null; } })();
const L = [];
L.push("# CLAIMS-INDEX — the fresh Verifier's one page (GENERATED by `node scripts/gen-claims-index.mjs` — state over ACCEPTANCE-RECEIPTS.txt " + (sealedOver ? sealedOver.slice(0, 16) + '…' : '(unsealed)') + ')');
L.push('');
L.push('Every claim in `claims.json` (the T2 protocol): what it asserts, the command that checks it, the stdout shape to expect, and the exit codes. **One command checks them all:** `node scripts/check-claims.mjs` (full phase, exit 0 = the package is green) and `node scripts/check-claims.mjs --phase packaging` (the mid-composite subset). A RED is a failing line — never a paragraph.');
L.push('');
L.push('| claim | phase | kind | the assertion | command | expected stdout shape | exit |');
L.push('|---|---|---|---|---|---|---|');
for (const c of claims.claims) {
  const phases = (c.phases || ['full']).join('+');
  const kc = KIND_CMD[c.kind] || { cmd: 'node scripts/check-claims.mjs', expect: '(checker-defined)', exit: '0 / 1' };
  const desc = (c.desc || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  const cmd = (c.cmd ? c.cmd.replace(/\|/g, '\\|') : kc.cmd);
  L.push(`| \`${c.id}\` | ${phases} | ${c.kind} | ${desc} | ${cmd} | ${kc.expect} | ${kc.exit} |`);
}
L.push('');
L.push('## The gate battery (the S17 work order §2 A7, run at the final bytes)');
L.push('');
L.push('```');
L.push('node tools/verify-package.mjs .                                            # seal green + converse clean');
L.push('node scripts/gate-manifest.mjs                                             # PASS');
L.push('node scripts/gate-numerals.mjs                                             # CLEAN ×2');
L.push('node scripts/check-claims.mjs --phase packaging                            # 0 RED, exit 0');
L.push('node scripts/check-claims.mjs                                              # 0 RED, exit 0');
L.push('node --test --experimental-strip-types test/engine.test.ts                 # 430 pass / 0 fail');
L.push('node --import ./scripts/node-port-register.mjs batteries/node.battery.mjs  # 37 pass / 0 fail');
L.push('npm run battery:board && npm run battery:slot && npm run battery:visual    # 24/0, 28/0, 18/0');
L.push('git -C <repo> archive 408410477 colors/src | tar -x -C <tmp>; diff -rq <tmp>/colors/src src/engine   # empty, 69 files');
L.push('```');
fs.writeFileSync(path.join(ROOT, 'deliveries', 'CLAIMS-INDEX.md'), L.join('\n') + '\n');
console.log(`gen-claims-index: deliveries/CLAIMS-INDEX.md written (${claims.claims.length} claims)`);
