#!/usr/bin/env node
/* gen-contract-golden.mjs — the Wave B #6 SEAM DRIFT ALARM (ernie A2): generate
 * src/lib/port/contract.golden.json — the JSON SHAPE of the seam's three core VMs (boardVM,
 * seasonVM, weekVM) at THIS pin — and the node battery law (N-golden-shape) recomputes the shape
 * at runtime and FAILS NAMING THE FIELD when a re-pin renames or removes a field the shell reads.
 * A structurally-compatible ADDITION is not a failure (the shell reads what it reads); a RENAME,
 * a REMOVAL, or a TYPE-CLASS CHANGE on a named leaf is.
 *
 * Test-only artifact: it rides the seal like any content file, but no UI reads it — it exists so
 * M3's swap test promotes from "it builds" to "the shape the shell consumes is intact".
 *
 * Run: node --import ./scripts/node-port-register.mjs scripts/gen-contract-golden.mjs
 * (regenerate ONLY at a deliberate re-pin, never casually — the golden IS the pin's shape)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const port = await import(path.join(ROOT, 'src/lib/port/seam.ts'));
const weekVMm = await import(path.join(ROOT, 'src/lib/port/weekVM.ts'));
const seasonVMm = await import(path.join(ROOT, 'src/lib/port/seasonVM.ts'));

// ---- build the three live VMs at a fixed seed (deterministic — the golden is reproducible) ----
const CSV = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const pool = port.buildPool(CSV('data/nfl/madden27-ratings.csv'), CSV('data/nfl/free-agents-old-ratings.csv'), CSV('data/nfl/player-ids.csv'));
const draft = port.newDraft(pool, port.makeRng(0xa3f2).fork('draft'), { ...port.DEFAULT_CONFIG, userTeam: 7, seed: 0xa3f2 });
// step the CPU picks until the USER's first pick (goneOdds asserts the position), take the board
// VM there — the SHAPE is what the golden records, and a mid-draft state is the board's live shape
const cpuRng = port.makeRng(0xa3f2).fork('run');
let steps = 0;
while (draft.order[draft.pos] !== 7 && steps < 64 && draft.pos < draft.order.length) {
  const team = draft.order[draft.pos];
  const c = port.cpuChoose(draft, team, cpuRng);
  port.applyPick(draft, team, c.player, c.slot);
  steps++;
}
const board = port.boardVM(draft, 7, port.goneOdds(draft, 7, port.makeRng(0xb3f2), 40));

// the season side: the drafted rosters become the LeagueTeams, one week is played, then the
// week-stepper view-models read the RunState
const teams = seasonVMm.leagueTeams(pool, draft.log);
let season = port.startSeason(teams, { seed: 0xa3f2, year: 2027 });
({ state: season } = port.playWeek(teams, season));
const week = weekVMm.weekView(season, 1);
const standings = weekVMm.standingsThrough(season, 1);

const typeOf = (v) => {
  if (v === null || v === undefined) return 'nullish';
  if (Array.isArray(v)) return 'array';
  if (typeof v === 'object') return 'object';
  return typeof v;   // 'string' | 'number' | 'boolean'
};
// shape(v): every object path → its TYPE CLASS; arrays by their element-0 shape (or 'array<scalar>')
const shape = (v, prefix, out, depth = 0) => {
  if (depth > 5) { out[prefix] = '…'; return; }
  const t = typeOf(v);
  if (t === 'object') {
    for (const [k, val] of Object.entries(v)) shape(val, prefix ? prefix + '.' + k : k, out, depth + 1);
    if (Object.keys(v).length === 0) out[prefix] = 'object{}';
  } else if (t === 'array') {
    out[prefix] = v.length && typeOf(v[0]) !== 'object' && typeOf(v[0]) !== 'array' ? 'array<' + typeOf(v[0]) + '>' : 'array';
    if (v.length && (typeOf(v[0]) === 'object')) shape(v[0], prefix + '[]', out, depth + 1);
  } else {
    out[prefix] = t;
  }
};

const out = {};
shape(board, 'boardVM', out);
shape(week, 'weekVM', out);
shape(standings, 'standingsVMw', out);

const golden = {
  meta: 'GENERATED by scripts/gen-contract-golden.mjs at pin ' + (port.engineVersion?.() ?? 'unknown') + ' — the SHAPE of the seam VMs the shell consumes (values never recorded; type classes only). The node battery law N-golden-shape recomputes the live shape and fails naming any field the shell reads that was RENAMED/REMOVED/retyped. Regenerate ONLY at a deliberate re-pin.',
  // item 3 (fixed point): the golden is DETERMINISTIC — the old wall-clock `generated` stamp
  // changed the bytes on every regeneration, so the close-out chain could not converge (the seal
  // re-hashed a new file each pass). The pin stamp IS the generation identity (the golden is the
  // pin's shape).
  engineVersion: port.engineVersion?.() ?? null,
  shapes: out,
};
fs.writeFileSync(path.join(ROOT, 'src/lib/port/contract.golden.json'), JSON.stringify(golden, null, 1) + '\n');
console.log(`gen-contract-golden: ${Object.keys(out).length} leaf paths recorded (boardVM + weekVM + standingsVMw)`);
