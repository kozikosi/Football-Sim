// Vite plugin: generate the service worker from the BUILD OUTPUT (w74 item 6a, Z.ai DRAFT).
//
// THE RULE (from the w74 review of Claude's §4–§7): the SW manifest must be build-output-derived, NOT
// hand-maintained, and it collapses all hashed chunks into ONE cache key per build so a stale-chunk bug cannot
// hide: every asset of this build lives in cache `colors-<buildHash>-v<manifestVersion>`; a build whose hash
// differs installs a NEW cache and deletes the old ones on activate. The engine and dataset are IN the bundle
// (single JS asset here), so there is no separate engine-choreography — the manifest is: the navigation target,
// every emitted asset, and nothing else.
//
// How it works: closeBundle reads Vite's own bundle summary (dist/), emits `dist/sw.js` = SW_SOURCE (below, the
// compiled sw.ts output is inlined by Vite as an asset? NO — sw.ts is compiled HERE, string-assembled: the SW is
// a tiny, dependency-free file; assembling it keeps the plugin the single source of truth for both the cache
// strategy and the manifest). The app never imports sw.js; main.ts registers it when the build flag is on.
//
// G-SW1 (flagged): hand-assembled SW string vs a real sw.ts compiled by Vite. I chose the string: a compiled sw
// would need code-splitting excludes and a second Vite build (sw entry), and the SW is ~120 lines — the string
// IS the review surface. If the Architect prefers a real file, the plugin swaps to emitFile and the logic moves
// unchanged.

import fs from 'node:fs';
import path from 'node:path';

export function serviceWorkerPlugin(o = { manifestVersion: 1 }) {
  let outDir = 'dist';
  return {
    name: 'colors-service-worker',
    apply: 'build',
    configResolved(cfg) { outDir = cfg.build.outDir || 'dist'; },
    closeBundle() {
      const dir = path.resolve(process.cwd(), outDir);
      const files = [];
      const walk = (d) => { for (const f of fs.readdirSync(d, { withFileTypes: true })) { const p = path.join(d, f.name); if (f.isDirectory()) walk(p); else files.push(path.relative(dir, p).split(path.sep).join('/')); } };
      if (fs.existsSync(dir)) walk(dir);
      const assets = files.filter((f) => f.startsWith('assets/'));
      const buildHash = assets.length ? (assets[0].match(/-([\w-]{8,})\.\w+$/) ?? [])[1] ?? 'dev' : 'dev';
      const cacheName = `colors-${buildHash}-v${o.manifestVersion}`;
      const sw = swSource({ cacheName, precache: ['/', ...assets], manifestVersion: o.manifestVersion });
      fs.writeFileSync(path.join(dir, 'sw.js'), sw);
      // A build receipt the evidence-pack script (item 7c) can pin: which cache owns this build.
      fs.writeFileSync(path.join(dir, 'sw-manifest.json'), JSON.stringify({ cacheName, buildHash, manifestVersion: o.manifestVersion, precache: ['/', ...assets] }, null, 2));
    },
  };
}

export function swSource({ cacheName, precache, manifestVersion }) {
  const list = JSON.stringify(precache);
  return `/* colors service worker — GENERATED by tools/vite-plugin-sw.mjs at build time. Do not edit; edit the plugin. */
const CACHE = ${JSON.stringify(cacheName)};
const MANIFEST_V = ${manifestVersion};
const PRECACHE = ${list};

self.skipWaiting();
self.addEventListener('activate', (e) => {
  e.waitUntil((async () => {
    // One cache per build: delete everything this build did not create (stale chunks cannot hide).
    for (const name of await caches.keys()) if (name !== CACHE) await caches.delete(name);
    await self.clients.claim();
  })());
});

self.addEventListener('install', (e) => {
  e.waitUntil((async () => { const c = await caches.open(CACHE); await c.addAll(PRECACHE); })());
});

// Navigations: STALE-WHILE-REVALIDATE — the cached shell answers FIRST (an offline-first game boots from cache,
// online or not), then a background refresh puts the fresh shell into the cache; the next reload gets it. This
// is also the robust choice: offline fetch(navigationRequest) + reload-request matching are Chromium quirks the
// w74 offline test caught on the first draft (the network-first variant served an empty body in exactly that
// combination). Freshness is not lost: skipWaiting means a new build takes over on the NEXT reload either way,
// and the update toast tells the user.
// VARY NOTE (the w74 offline test's real bug): vite preview sends a 'Vary: Origin' header. Precache entries are stored
// from no-cors requests (no Origin header), but module scripts fetch with mode 'cors' and DO carry Origin —
// Cache.match's Vary check then MISSES the same URL. Every match below uses ignoreVary: our cache holds only
// our own build artifacts, all equivalent for any Origin the app itself requests.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith((async () => {
      const cached = await caches.match('/', { ignoreVary: true, ignoreSearch: true });
      const refresh = fetch(req).then(async (fresh) => {
        if (fresh && fresh.ok) { const c = await caches.open(CACHE); await c.put('/', fresh.clone()); }
        return fresh;
      }).catch(() => null);
      return cached || (await refresh) || Response.error();
    })());
    return;
  }
  if (url.pathname.startsWith('/assets/')) {
    e.respondWith((async () => (await caches.match(req, { ignoreVary: true })) || fetch(req))());
  }
});

// The update toast: the app asks, the SW answers with what it knows.
self.addEventListener('message', (e) => {
  if (e.data === 'sw:state') e.source?.postMessage({ type: 'sw:state', cache: CACHE, manifestVersion: MANIFEST_V, precache: PRECACHE.length });
});
`;
}
