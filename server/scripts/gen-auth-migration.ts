// Regenerates migrations/0002_better_auth.sql from the installed Better Auth version.  Run: node --experimental-strip-types scripts/gen-auth-migration.ts
// The committed file is what `wrangler d1 migrations apply` runs; test/auth-migration.test.ts fails if a Better Auth upgrade changes the schema.
import { DatabaseSync } from 'node:sqlite';
import { writeFileSync } from 'node:fs';
import { getMigrations } from 'better-auth/db/migration';
import { authOptions } from '../src/auth.ts';

export async function compileAuthSql(): Promise<string> {
  const opts = authOptions({ DB: new DatabaseSync(':memory:'), BASE_URL: 'https://example.invalid', BETTER_AUTH_SECRET: 'x'.repeat(40), GITHUB_CLIENT_ID: 'x', GITHUB_CLIENT_SECRET: 'x' });
  const { compileMigrations } = await getMigrations(opts as never);
  return await compileMigrations();
}
if (process.argv[1] && process.argv[1].endsWith('gen-auth-migration.ts')) {
  const sql = await compileAuthSql();
  writeFileSync(new URL('../migrations/0002_better_auth.sql', import.meta.url), '-- GENERATED by scripts/gen-auth-migration.ts from the installed better-auth; do not edit by hand.\n' + sql.trim() + '\n');
  console.log('wrote migrations/0002_better_auth.sql (' + sql.length + ' chars)');
}
